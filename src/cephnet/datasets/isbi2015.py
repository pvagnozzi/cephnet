from __future__ import annotations

import logging
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
import torch

from cephnet.datasets.base import BaseDataset

logger = logging.getLogger(__name__)

N_LANDMARKS = 19
PIXEL_SPACING = 0.1  # mm per pixel


class ISBI2015Dataset(BaseDataset):
    """ISBI 2015 Cephalometric Challenge dataset.

    Expected on-disk layout::

        <root>/
          images/          # *.png files named by image_id
          annotations/
            landmarks.csv  # columns: image_id, lm_0_x, lm_0_y, …, lm_18_x, lm_18_y
    """

    N_LANDMARKS: int = 19
    PIXEL_SPACING_MM: float = 0.1

    def __init__(
        self,
        root: Path,
        split: str = "train",
        image_size: tuple[int, int] = (512, 512),
        train_ratio: float = 0.6,
        val_ratio: float = 0.2,
        seed: int = 42,
        transform: object | None = None,
    ) -> None:
        self._train_ratio = train_ratio
        self._val_ratio = val_ratio
        self._seed = seed
        super().__init__(root=root, split=split, image_size=image_size, transform=transform)

    @property
    def n_landmarks(self) -> int:
        return self.N_LANDMARKS

    @property
    def pixel_spacing_mm(self) -> float:
        return self.PIXEL_SPACING_MM

    def _load_samples(self) -> None:
        annotations_path = self.root / "annotations" / "landmarks.csv"
        images_dir = self.root / "images"

        if not annotations_path.exists():
            logger.warning(
                "⚠️  ISBI2015 dataset not found at %s — using in-memory synthetic data",
                self.root,
            )
            logger.warning(
                "   Run: scripts\\windows\\run_prepare.ps1 -Config configs/training/quick_test.yaml"
                " to generate data on disk."
            )
            self._samples = self._create_synthetic_samples()
            return

        df = pd.read_csv(annotations_path)

        # Support both CSV formats:
        #   1. Generated by DatasetPreparer: has a 'split' column
        #   2. Real ISBI2015 format: no 'split' column, images in flat images/ dir
        if "split" in df.columns:
            split_df = df[df["split"] == self.split]
        else:
            # Legacy: deterministic ratio-based split by row index
            rng = np.random.default_rng(self._seed)
            indices = rng.permutation(len(df)).tolist()
            n_total = len(indices)
            n_train = int(n_total * self._train_ratio)
            n_val = int(n_total * self._val_ratio)
            if self.split == "train":
                selected = indices[:n_train]
            elif self.split == "val":
                selected = indices[n_train : n_train + n_val]
            else:
                selected = indices[n_train + n_val :]
            split_df = df.iloc[selected]

        self._samples = []
        for _, row in split_df.iterrows():
            img_id = str(row["image_id"])
            # Try split subdirectory first, then flat images/ directory
            img_path = images_dir / self.split / f"{img_id}.png"
            if not img_path.exists():
                img_path = images_dir / f"{img_id}.png"

            lm_cols_x = [f"lm_{i}_x" for i in range(self.N_LANDMARKS)]
            lm_cols_y = [f"lm_{i}_y" for i in range(self.N_LANDMARKS)]
            if not all(c in row.index for c in lm_cols_x + lm_cols_y):
                continue
            landmarks = np.array(
                [
                    [float(row[f"lm_{i}_x"]), float(row[f"lm_{i}_y"])]
                    for i in range(self.N_LANDMARKS)
                ],
                dtype=np.float32,
            )
            self._samples.append({"image_path": img_path, "landmarks": landmarks})

        logger.info("✅ ISBI2015 %s split: %d samples", self.split, len(self._samples))

    def _create_synthetic_samples(self) -> list[dict[str, Any]]:
        """Create in-memory synthetic samples when real data is absent."""
        rng = np.random.default_rng(42)
        n_samples = {"train": 20, "val": 6, "test": 6}.get(self.split, 10)
        samples: list[dict[str, Any]] = []
        for i in range(n_samples):
            samples.append(
                {
                    "image_path": Path(f"synthetic/isbi2015/{self.split}/{i:04d}.png"),
                    "landmarks": rng.uniform(50, 462, size=(self.N_LANDMARKS, 2)).astype(
                        np.float32
                    ),
                    "_synthetic": True,
                }
            )
        return samples

    def __getitem__(self, idx: int) -> dict[str, Any]:
        sample = self._samples[idx]
        if sample.get("_synthetic"):
            rng = np.random.default_rng(idx)
            image_t = torch.from_numpy(
                rng.random((3, self.image_size[1], self.image_size[0])).astype(np.float32)
            )
            landmarks_t = torch.from_numpy(sample["landmarks"])
            return {
                "image": image_t,
                "landmarks": landmarks_t,
                "image_path": str(sample["image_path"]),
            }
        return super().__getitem__(idx)
